# Iteratively loudness-matches the factory presets: render, measure, write PresetTrims.h, rebuild.
import subprocess, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = float(sys.argv[1]) if len(sys.argv) > 1 else -16.0
ENV = dict(os.environ, CPATH="/home/claude/deps/xstubs")
OUT = "/tmp/bndt_out"

def build():
    subprocess.run(["cmake", "--build", "build-linux", "--target", "bndt_test", "-j4"], cwd=ROOT, env=ENV,
                   check=True, stdout=subprocess.DEVNULL)

def run():
    subprocess.run(["xvfb-run", "-a", "build-linux/bndt_test_artefacts/Release/bndt_test", OUT], cwd=ROOT,
                   check=True, stdout=subprocess.DEVNULL)
    rows = {}
    for line in open(os.path.join(OUT, "trims.tsv")):
        _, name, mom, master = line.rstrip("\n").split("\t")
        rows[name] = (float(mom), float(master))
    return rows

def write(trims):
    with open(os.path.join(ROOT, "Source", "PresetTrims.h"), "w") as f:
        f.write("#pragma once\n#include <utility>\n// Generated by tools/match_levels.py: preset name -> master trim (dB)\n")
        f.write("static const std::pair<const char*, float> kTrims[] = {\n")
        for n, t in trims.items():
            f.write('    { "%s", %.1ff },\n' % (n, t))
        f.write("};\n")

for it in range(4):
    build()
    rows = run()
    trims, worst = {}, 0.0
    for n, (mom, master) in rows.items():
        err = TARGET - mom
        worst = max(worst, abs(err))
        trims[n] = max(-30.0, min(12.0, round((master + err) * 2) / 2))
    print("pass", it, "worst error %.1f dB" % worst)
    for n, (mom, master) in rows.items():
        if abs(TARGET - mom) > 1.5: print("   %-22s mom %.1f master %.1f -> %.1f" % (n, mom, master, trims[n]))
    write(trims)
    if worst < 1.0: break
